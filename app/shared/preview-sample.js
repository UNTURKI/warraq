/** يضيف بادئة إلى كل المعرّفات (عناوين وحواشٍ) حتى تجتمع المقاطع في مستند واحد بلا تعارض */
function prefixed(doc, pre) {
  const id = (x) => pre + x;
  const blocks = doc.blocks.map((b) => {
    const n = { ...b };
    if (n.id) n.id = id(n.id);
    if (n.poem != null) n.poem = pre + n.poem;
    if (n.runs) n.runs = n.runs.map((r) => (r.id ? { ...r, id: id(r.id) } : r));
    return n;
  });
  const notes = Object.fromEntries(Object.entries(doc.notes).map(([k, v]) => [id(k), v]));
  const headings = doc.headings.map((h) => ({ ...h, id: id(h.id) }));
  return { blocks, notes, headings };
}

