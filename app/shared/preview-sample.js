function buildMutunPreview(s, po, own) {
  const ms = { ...s, mRange: { mode: 'all' } };
  const prose = composeVolume(parse(MPROSE, po), { ...ms, mDivide: s.mDivide === 'verses' ? 'heads' : s.mDivide });
  const poem = composeVolume(parse(MPOEM, po), { ...ms, mDivide: s.mDivide === 'auto' ? 'verses' : s.mDivide, mCount: s.mDivide === 'auto' || s.mDivide === 'verses' ? Math.min(s.mCount || 5, 6) : s.mCount });
  const doc = { blocks: [], notes: {}, headings: [], bookHasMatn: false, layout: 'plain', mutun: poem.mutun };
  const marks = {};
  // متن المستخدم (أول أجزائه، مركّباً بإعداداته وتعديلاته): لوحةٌ بعد النموذجين
  const parts = [['heads', 'A-', prose], ['sharhPage', 'B-', poem]];
  if (own && Array.isArray(own.blocks) && own.blocks.length) parts.push(['sharhOrn', 'C-', { notes: {}, headings: [], ...own }]);
  for (const [key, pre, composed] of parts) {
    const p = prefixed(composed, pre);
    // كل لوحة تبدأ في صفحة جديدة
    if (key !== 'heads' && p.blocks.length) p.blocks[0] = { ...p.blocks[0], breakBefore: true };
    marks[key] = p.blocks.find((b) => b.id)?.id || null;
    doc.blocks.push(...p.blocks);
    Object.assign(doc.notes, p.notes);
    doc.headings.push(...p.headings);
  }
  return { doc, cover: { ...SAMPLE_COVER, title: 'عنوان المتن', author: 'اسم المؤلف' }, marks };
}

/**
 * يبني مستند المعاينة من الإعدادات الحالية.
 * @param {object} settings      إعدادات كاملة (كما تُرسل للتنضيد)
 * @param {object} [opts]        { cover, parseOpts: { matnQawluhu }, own: متن المستخدم مركّباً (المتون) }
 * @returns {{doc: object, cover: object, marks: object}}  marks: معرّف أول عنصر في كل لوحة
 */
export function buildPreviewDoc(settings, opts = {}) {
  const s = settings;
  const po = { matnQawluhu: true, mergeBrokenParagraphs: true, ...(opts.parseOpts || {}) };
  if (s.template === 'research') return buildResearchPreview(s, po);
  if (s.mutun) return buildMutunPreview(s, po, opts.own || null);
  const withNotes = s.footnotes !== false;
  const parts = [
    // العناوين والمتن: نص عادي بعناوينه وحواشيه
    ['heads', 'A-', composeVolume(parse(HEADS, po), { ...s, template: withNotes ? 'matn_hashia' : 'matn' })],
    // المتن والشرح بطريقتي «نهاية الشرح»
    ['sharhPage', 'B-', composeVolume(parse(SHARH, po), { ...s, template: withNotes ? 'full' : 'matn_sharh', sharhEnd: 'page' })],
    ['sharhOrn', 'C-', composeVolume(parse(SHARH, po), { ...s, template: withNotes ? 'full' : 'matn_sharh', sharhEnd: 'ornament' })],
    ['verses', 'D-', composeVolume(parse(VERSES, po), { ...s, template: withNotes ? 'full' : 'matn_sharh', sharhEnd: 'page' })],
  ];
  const doc = { blocks: [], notes: {}, headings: [], bookHasMatn: true, layout: 'plain' };
  const marks = {};
  for (const [key, pre, composed] of parts) {
    const p = prefixed(composed, pre);
    // نظام العناوين: لوحة «العناوين والمتن» وحدها تُري صفحة الباب المستقلة وبدء الفصل في صفحة فردية؛
    // وفي غيرها تبقى العناوين بشكلها في مجرى النص (hsFlow)، فتظهر الأبيات والشرح في أول صفحات اللوحة
    if (key !== 'heads') p.blocks = p.blocks.map((b) => (b.type === 'heading' && b.hr ? { ...b, hsFlow: true } : b));
    // كل لوحة تبدأ في صفحة جديدة
    if (!p.blocks.length) continue;
    p.blocks[0] = { ...p.blocks[0], breakBefore: true };
    marks[key] = p.blocks.find((b) => b.id)?.id || null;
    doc.blocks.push(...p.blocks);
    Object.assign(doc.notes, p.notes);
    // الفهرس: بلا تكرار «باب الكلام» من اللوحة الثانية للشرح
    if (key !== 'sharhOrn') doc.headings.push(...p.headings);
  }
  return { doc, cover: { ...SAMPLE_COVER, ...(opts.cover || {}) }, marks };
}
